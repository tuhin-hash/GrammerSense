"""
Candidate generation, scoring, and ranking module.
Applies beam decoding outputs, minimal necessary edit heuristics,
and calibrated sequence confidence ranking.
"""

from typing import List, Dict, Any, Tuple
import difflib


class CandidateCorrection:
    """Represents a candidate correction with rank, confidence, and linguistic score."""

    def __init__(
        self,
        candidate_text: str,
        rank: int,
        confidence: float,
        edit_distance: int,
        rank_score: float,
        is_selected: bool = False,
    ):
        self.candidate_text = candidate_text
        self.rank = rank
        self.confidence = confidence
        self.edit_distance = edit_distance
        self.rank_score = rank_score
        self.is_selected = is_selected

    def to_dict(self) -> Dict[str, Any]:
        return {
            "candidate_text": self.candidate_text,
            "rank": self.rank,
            "confidence": round(self.confidence, 4),
            "edit_distance": self.edit_distance,
            "rank_score": round(self.rank_score, 4),
            "is_selected": self.is_selected,
        }

    def __repr__(self) -> str:
        return f"CandidateCorrection(rank={self.rank}, conf={self.confidence}, text={self.candidate_text!r})"


class CandidateSelector:
    """Selects and ranks candidate corrections generated by sequence-to-sequence beam search."""

    @classmethod
    def select_best(
        cls,
        source_text: str,
        raw_candidates: List[Tuple[str, float]],
        alpha: float = 0.8,
        beta: float = 0.2,
    ) -> Tuple[CandidateCorrection, List[CandidateCorrection]]:
        """
        Ranks candidate corrections using a combination of model beam confidence
        and minimal-edit preservation.
        
        Args:
            source_text: Original raw input string.
            raw_candidates: List of (candidate_text, model_prob) from beam search.
            alpha: Weight for model sequence probability.
            beta: Weight for edit penalty (favoring minimal gratuitous changes).
            
        Returns:
            Tuple of (best_candidate, sorted_all_candidates)
        """
        if not raw_candidates:
            fallback = CandidateCorrection(
                candidate_text=source_text,
                rank=1,
                confidence=1.0,
                edit_distance=0,
                rank_score=1.0,
                is_selected=True,
            )
            return fallback, [fallback]

        scored: List[Dict[str, Any]] = []
        source_tokens = source_text.split()
        src_len = max(1, len(source_tokens))

        for cand_text, model_prob in raw_candidates:
            cand_tokens = cand_text.split()
            # Calculate token-level Levenshtein edit distance between source and candidate
            matcher = difflib.SequenceMatcher(None, source_tokens, cand_tokens)
            edits = sum(1 for tag, _, _, _, _ in matcher.get_opcodes() if tag != "equal")

            # Normalized edit ratio relative to source length
            edit_ratio = edits / (src_len + 1)

            # Rank score balances model confidence with minimal necessary semantic alteration
            # If source is already identical to candidate, reward stability
            stability_bonus = 0.05 if cand_text.strip() == source_text.strip() else 0.0
            rank_score = (alpha * model_prob) - (beta * edit_ratio) + stability_bonus

            scored.append({
                "text": cand_text,
                "confidence": model_prob,
                "edit_distance": edits,
                "rank_score": rank_score,
            })

        # Sort by rank_score descending
        scored.sort(key=lambda x: x["rank_score"], reverse=True)

        candidate_objects: List[CandidateCorrection] = []
        for idx, item in enumerate(scored):
            is_best = (idx == 0)
            candidate_objects.append(
                CandidateCorrection(
                    candidate_text=item["text"],
                    rank=idx + 1,
                    confidence=item["confidence"],
                    edit_distance=item["edit_distance"],
                    rank_score=item["rank_score"],
                    is_selected=is_best,
                )
            )

        best_cand = candidate_objects[0]
        return best_cand, candidate_objects
